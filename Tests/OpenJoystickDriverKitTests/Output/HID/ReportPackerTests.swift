import Testing

@testable import OpenJoystickDriverKit

struct HIDReportPackerTests {
  private let descriptor: [UInt8] = [
    0x05, 0x01,  // Generic Desktop
    0x09, 0x05,  // Game Pad
    0xA1, 0x01,  // Application
    0x05, 0x09,  // Button
    0x09, 0x01,  // Button 1
    0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x01, 0x81, 0x02, 0x75, 0x07, 0x95, 0x01, 0x81, 0x03,
    0x06, 0x00, 0xFF,  // Vendor page 0xFF00
    0x09, 0x01,  // Vendor usage 1
    0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x01, 0x81, 0x02, 0x75, 0x07, 0x95, 0x01, 0x81, 0x03,
    0xC0,
  ]

  @Test
  func usagePageKeepsSameNumberedInputsDistinct() throws {
    let format = try HIDDescriptorReportFormat(descriptor: descriptor)

    // Normalized button 0 is Button-page usage 1, not the vendor-page usage 1 beside it.
    #expect(format.buildInputReport(from: VirtualGamepadState(buttons: 1)) == [0x01, 0x00])
  }
}
